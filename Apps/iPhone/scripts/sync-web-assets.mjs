import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const desktop = path.resolve(root, "../../Resources/Dashboard");
const names = ["Readability.js", "purify.min.js", "article-extraction.js"];
for (const name of names)
  fs.copyFileSync(
    path.join(
      desktop,
      name === "article-extraction.js" ? name : "Vendor/" + name,
    ),
    path.join(root, "assets/vendor", name),
  );
for (const name of ["Readability-LICENSE.md", "DOMPurify-LICENSE"])
  fs.copyFileSync(
    path.join(desktop, "Vendor", name),
    path.join(root, "assets/vendor/licenses", name),
  );
const read = (name) =>
  fs.readFileSync(path.join(root, "assets/vendor", name), "utf8");
fs.writeFileSync(
  path.join(root, "src/lib/vendor.ts"),
  "// Generated by npm run assets from shared desktop sources; do not edit.\nexport const extractionScripts=" +
    JSON.stringify(names.map(read).join("\n")) +
    ";\nexport const purifyScript=" +
    JSON.stringify(read("purify.min.js")) +
    ";\n",
);
