import { toByteArray, fromByteArray } from "base64-js";
import { webURL } from "./model";
export const standard64 = (s: string) =>
  s.replace(/-/g, "+").replace(/_/g, "/") +
  "=".repeat((4 - (s.length % 4)) % 4);
export const decode64 = (s: string) => toByteArray(standard64(s));
export const encode64 = (bytes: Uint8Array) =>
  fromByteArray(bytes)
    .replace(/=/g, "")
    .replace(/\+/g, "-")
    .replace(/\//g, "_");
export type SetupLink = { v: 1; endpoint: string; token: string; key: string };
export function setupLink(raw: string): SetupLink | undefined {
  const url = new URL(raw.trim());
  const value = new URLSearchParams(url.hash.slice(1)).get("read-setup");
  if (!value) return;
  if (value.length > 4000) throw new Error("Invalid setup link.");
  const p = JSON.parse(new TextDecoder().decode(decode64(value)));
  const endpoint = webURL(p.endpoint);
  if (
    new URL(endpoint).protocol !== "https:" ||
    p.v !== 1 ||
    !/^[A-Za-z0-9_-]{40,100}$/.test(p.token) ||
    decode64(p.key).length !== 32
  )
    throw new Error("Use the private HTTPS setup link generated by your Mac.");
  return { v: 1, endpoint, token: p.token, key: p.key };
}
export function validateProfile(p: any) {
  if (p?.version !== 1 || !p.settings || !p.secrets)
    throw new Error("This setup profile is not supported.");
  if (
    p.expiresAt !== undefined &&
    (!Number.isFinite(p.expiresAt) || p.expiresAt < Date.now())
  )
    throw new Error("This private setup profile has expired.");
  const opds = p.settings.opds ? webURL(p.settings.opds) : "",
    sync = p.settings.sync ? webURL(p.settings.sync) : "";
  if (!opds && !sync && !p.secrets.readwise && !p.secrets.hardcover)
    throw new Error("No connections found in this setup profile.");
  if (!Array.isArray(p.catalog?.records) || p.catalog.records.length > 20000)
    throw new Error("Invalid Calibre catalog snapshot.");
  if (
    p.highlights !== undefined &&
    (!Array.isArray(p.highlights) || p.highlights.length > 20000)
  )
    throw new Error("Invalid highlight snapshot.");
  return {
    ...p,
    settings: {
      opds,
      sync,
      username: String(p.settings.username || "").slice(0, 200),
      readerSync: !!p.secrets.readwise,
      onboarded: true,
    },
  };
}
