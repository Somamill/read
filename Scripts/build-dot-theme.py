"""Generate read.'s platform adapters from the checked-in dot. brand tokens."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def outputs():
    tokens = json.loads((ROOT / 'branding/dot/tokens.json').read_text())
    colors = tokens['colors']
    css = ['/* Generated by Scripts/build-dot-theme.py; semantic dot. adapter. */']
    for theme in ('light', 'dark'):
        selector = ':root' if theme == 'light' else 'html[data-theme="dark"]'
        values = {f'--dot-{key}': value for key, value in colors[theme].items()}
        if theme == 'light':
            values.update({f'--dot-space-{k}': f'{v}px' for k, v in tokens['spacing'].items()})
            values.update({f'--dot-radius-{k}': f'{v}px' for k, v in tokens['radius'].items()})
            values['--dot-accent'] = colors['accents']['read']
            values['--dot-font'] = '-apple-system, BlinkMacSystemFont, system-ui, sans-serif'
        css.append(selector + '{' + ';'.join(f'{k}:{v}' for k,v in values.items()) + '}')
    css.append('html[data-appearance="oled"]{--dot-background:#000000;--dot-surface:#111411}')
    ts = '// Generated by Scripts/build-dot-theme.py; do not edit.\nexport const dot = ' + json.dumps(tokens, indent=2) + ' as const;\n'
    return {'Resources/Dashboard/dot-theme.json': json.dumps(tokens, indent=2)+'\n',
            'Resources/Dashboard/dot-tokens.css': '\n'.join(css)+'\n',
            'Apps/iPhone/src/lib/dot-theme.ts': ts}

if __name__ == '__main__':
    import sys
    for name, content in outputs().items():
        path = ROOT / name
        if '--check' in sys.argv:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Outdated dot. adapter: '+name)
        else:
            path.write_text(content)
